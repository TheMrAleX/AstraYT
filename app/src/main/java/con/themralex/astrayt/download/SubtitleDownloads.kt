package con.themralex.astrayt.download

import android.content.Context
import con.themralex.astrayt.youtube.*
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.*
import kotlinx.coroutines.flow.*
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import okhttp3.*
import okhttp3.HttpUrl.Companion.toHttpUrl
import java.io.*
import java.util.concurrent.TimeUnit
import javax.inject.*

@Singleton class SubtitleDownloads @Inject constructor(@ApplicationContext private val context:Context,private val client:OkHttpClient) {
    private val _changes=MutableSharedFlow<String>(extraBufferCapacity=16)
    val changes=_changes.asSharedFlow()
    fun hasDownload(id:String,language:String?)=folder(id).listFiles()?.any{it.isFile && it.length()>0 && it.name.startsWith("download-${language.orEmpty()}-") && it.extension=="srt"}==true
    private fun folder(id:String)=File(context.filesDir,"subtitles/$id").apply{require(id.matches(Regex("[A-Za-z0-9_-]{11}")));mkdirs()}
    @Synchronized fun saveTimeline(id:String,cuts:List<Cut>){
        val previous=timeline(id)
        atomic(File(folder(id),"timeline.json"),Json.encodeToString(cuts))
        if(previous!=cuts)folder(id).listFiles()?.filter{it.name.startsWith("download-") && it.extension=="srt"}?.forEach{it.delete()}
    }
    fun timeline(id:String):List<Cut> = runCatching{Json.decodeFromString<List<Cut>>(File(folder(id),"timeline.json").readText())}.getOrDefault(emptyList())
    @Synchronized private fun atomic(file:File,text:String){val part=File(file.parentFile,file.name+".part");try{FileOutputStream(part).use{it.write(text.toByteArray(Charsets.UTF_8));it.fd.sync()};if(!part.renameTo(file))throw IOException("STORAGE")}finally{part.delete()}}
    suspend fun download(id:String,track:SubtitleOption,cuts:List<Cut>?=null):File=withContext(Dispatchers.IO) {
        val original=track.url.toHttpUrl()
        require(original.isHttps && (original.host=="youtube.com" || original.host.endsWith(".youtube.com")))
        val url=original.newBuilder().setQueryParameter("fmt","vtt").build()
        val text=runInterruptible {
            val call=client.newCall(Request.Builder().url(url).header("User-Agent","Mozilla/5.0").build()).apply{timeout().timeout(20,TimeUnit.SECONDS)}
            try{call.execute().use{response->
                if(!response.isSuccessful || response.body.contentLength()>10*1024*1024)throw IOException("SUBTITLE_DOWNLOAD")
                val buffer=ByteArray(16384);val output=ByteArrayOutputStream()
                response.body.byteStream().use{input->while(true){if(Thread.currentThread().isInterrupted)throw InterruptedException();val n=input.read(buffer);if(n<0)break;if(output.size()+n>10*1024*1024)throw IOException("SUBTITLE_SIZE");output.write(buffer,0,n)}}
                output.toString(Charsets.UTF_8.name())
            }}finally{call.cancel()}
        }
        val cues=SubtitlePolicy.parseVtt(text);if(cues.isEmpty())throw IOException("SUBTITLE_DOWNLOAD")
        currentCoroutineContext().ensureActive()
        val file=synchronized(this@SubtitleDownloads){
            val current=timeline(id)
            if(cuts!=null && cuts!=current)throw IOException("SUBTITLE_TIMELINE")
            val adjusted=SubtitlePolicy.retime(cues,current)
            if(adjusted.isEmpty())throw IOException("SUBTITLE_DOWNLOAD")
            val language=track.language.replace(Regex("[^A-Za-z0-9-]"),"_").take(35)
            File(folder(id),"download-$language-${if(track.autoGenerated)"auto"else"manual"}.srt").also{atomic(it,SubtitlePolicy.srt(adjusted))}
        }
        _changes.tryEmit(id);file
    }
}
