@Composable internal fun CaptureSubtitles(details:VideoDetails,state:CaptureState,model:CaptureModel){
    val c=SingularityTheme.colors;val motion=SingularityTheme.motion.enabled
    var expanded by rememberSaveable(details.ytId){mutableStateOf(false)}
    val selected=details.subtitles.firstOrNull{it.id==state.subtitleId}
    OptionRow(Icons.Rounded.ClosedCaption,stringResource(R.string.subtitles),{expanded=!expanded},value=selected?.label ?: stringResource(R.string.subtitles_off))
    AnimatedVisibility(expanded,enter=expandVertically(tween(if(motion)220 else 0))+fadeIn(tween(if(motion)160 else 0)),exit=shrinkVertically(tween(if(motion)180 else 0))+fadeOut(tween(if(motion)120 else 0))){
        Column(verticalArrangement=Arrangement.spacedBy(4.dp)){
            Text(stringResource(R.string.subtitle_capture_body),color=c.low,style=SingularityTheme.type.caption,modifier=Modifier.padding(horizontal=12.dp,vertical=8.dp))
            OptionRow(null,stringResource(R.string.subtitles_off),{model.subtitle(null)},selected=state.subtitleId==null)
            SubtitleChoices(details.subtitles,state.subtitleId,model::subtitle)
            if(details.subtitles.isEmpty())Text(stringResource(R.string.subtitle_none),color=c.mid,style=SingularityTheme.type.body,modifier=Modifier.padding(12.dp))
            RememberChoice(state.rememberSubtitles,model::rememberSubtitles)
        }
    }
}
@Composable private fun SubtitleChoices(tracks:List<SubtitleOption>,selected:String?,onChoose:(String)->Unit){
    var query by remember(tracks){mutableStateOf("")}
    val initial=remember(tracks){selected}
    val ordered=remember(tracks,initial){tracks.sortedWith(compareBy<SubtitleOption>{it.id!=initial}.thenBy{it.language.substringBefore('-')!=Locale.getDefault().language}.thenBy{it.autoGenerated}.thenBy{it.label})}
    if(tracks.size>8)LinkField(query,{query=it},stringResource(R.string.search),{})
    val filtered=remember(ordered,query){ordered.filter{it.label.contains(query,true) || it.language.contains(query,true) || Locale.forLanguageTag(it.language).displayName.contains(query,true)}}
    if(tracks.size>4)LazyColumn(Modifier.fillMaxWidth().heightIn(max=300.dp)){
        items(filtered,key={it.id},contentType={"subtitle-choice"}){track->SubtitleRow(track,selected==track.id){onChoose(track.id)}}
    }else filtered.forEach{track->SubtitleRow(track,selected==track.id){onChoose(track.id)}}
    if(tracks.isNotEmpty() && filtered.isEmpty())Text(stringResource(R.string.no_results),color=SingularityTheme.colors.mid,modifier=Modifier.padding(12.dp))
}
@Composable internal fun SubtitleRow(track:SubtitleOption,selected:Boolean,onClick:()->Unit){OptionRow(Icons.Rounded.Translate,track.label,onClick,detail=stringResource(if(track.autoGenerated)R.string.subtitle_automatic else R.string.subtitle_manual),selected=selected)}
@Composable fun VideoExtrasHost(model:VideoExtrasModel){
    val state by model.subtitle.collectAsStateWithLifecycle();val video=state.video ?: return
    val export=rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/x-subrip")){uri->if(uri!=null)model.exportSubtitle(uri)}
    SingularitySheet(model::closeSubtitles){
        SheetHeading(stringResource(R.string.subtitle_download),model::closeSubtitles)
        Text(video.title,color=SingularityTheme.colors.mid,style=SingularityTheme.type.caption,maxLines=2)
        when{
            state.loading->{IndeterminateProgressLine();Text(stringResource(R.string.subtitle_finding),color=SingularityTheme.colors.mid)}
            state.file!=null->{
                Text(stringResource(R.string.subtitle_saved),color=SingularityTheme.colors.text,style=SingularityTheme.type.body)
                Text(stringResource(R.string.subtitle_saved_body),color=SingularityTheme.colors.mid,style=SingularityTheme.type.caption)
                Row(horizontalArrangement=Arrangement.spacedBy(8.dp)){
                    SingularityButton(stringResource(R.string.subtitle_export),{export.launch(video.title.take(80)+".srt")},Modifier.weight(1f),variant="secondary")
                    SingularityButton(stringResource(R.string.accept),model::closeSubtitles,Modifier.weight(1f))
                }
            }
            else->{
                if(state.error)Text(stringResource(if(state.timelineMissing)R.string.subtitle_timeline_missing else R.string.subtitle_failed),color=SingularityTheme.colors.error,style=SingularityTheme.type.body)
                if(state.tracks.isEmpty()){
                    if(!state.error)Text(stringResource(R.string.subtitle_none),color=SingularityTheme.colors.mid,style=SingularityTheme.type.body)
                    SingularityButton(stringResource(R.string.retry),{model.openSubtitles(video)},Modifier.fillMaxWidth(),variant="secondary")
                }else{
                    SubtitleChoices(state.tracks,state.selected,model::chooseSubtitle)
                    RememberChoice(state.remember,model::rememberSubtitle)
                    if(state.downloading)IndeterminateProgressLine()
                    SingularityButton(stringResource(if(state.downloading)R.string.subtitle_downloading else R.string.subtitle_download),model::downloadSubtitle,Modifier.fillMaxWidth(),enabled=!state.downloading && !state.timelineMissing)
                }
            }
        }
    }
}
