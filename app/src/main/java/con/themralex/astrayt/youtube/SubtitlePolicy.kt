package con.themralex.astrayt.youtube

import con.themralex.astrayt.download.Cut
import java.util.Locale

internal data class SubtitleCue(val startUs:Long,val endUs:Long,val text:String)
internal object SubtitlePolicy {
    fun select(tracks:List<SubtitleOption>,language:String):SubtitleOption? = tracks.filter{it.language.substringBefore('-').equals(language.substringBefore('-'),true)}.minWithOrNull(compareBy<SubtitleOption>{!it.language.equals(language,true)}.thenBy{it.autoGenerated})
    fun restore(tracks:List<SubtitleOption>,remembered:String?,explicit:Boolean,id:String?):SubtitleOption? = if(explicit)tracks.firstOrNull{it.id==id}else remembered?.let{select(tracks,it)}
    fun timestamp(value:String):Long? {
        val match=Regex("(?:(\\d+):)?(\\d{2}):(\\d{2})[.,](\\d{3})").matchEntire(value) ?: return null
        val hours=match.groupValues[1].ifEmpty{"0"}.toLongOrNull() ?: return null
        val minutes=match.groupValues[2].toLong();val seconds=match.groupValues[3].toLong()
        if(hours>10000 || minutes>59 || seconds>59)return null
        return ((hours*3600+minutes*60+seconds)*1000+match.groupValues[4].toLong())*1000
    }
    fun parseVtt(content:String):List<SubtitleCue> {
        val lines=content.removePrefix("\uFEFF").replace("\r","").lines();val cues=mutableListOf<SubtitleCue>();var i=0
        while(i<lines.size){
            val timing=lines[i++].trim();if("-->" !in timing)continue
            val parts=timing.split("-->",limit=2)
            val start=timestamp(parts[0].trim()) ?: continue
            val end=timestamp(parts[1].trim().takeWhile{!it.isWhitespace()}) ?: continue
            val text=org.jsoup.parser.Parser.unescapeEntities(buildList{while(i<lines.size && lines[i].isNotBlank())add(lines[i++])}.joinToString("\n")
                .replace(Regex("<br\\s*/?>",RegexOption.IGNORE_CASE),"\n").replace(Regex("<[^>]*>"),""),false).trim()
            if(end>start && text.isNotBlank())cues.add(SubtitleCue(start,end,text))
            if(cues.size>100000)throw java.io.IOException("SUBTITLE_SIZE")
        }
        return cues.distinct().sortedBy{it.startUs}
    }
    fun retime(cues:List<SubtitleCue>,cuts:List<Cut>):List<SubtitleCue> = cues.flatMap { cue->
        var start=cue.startUs;val kept=mutableListOf<SubtitleCue>()
        fun append(end:Long){if(end>start){val shifted=start-cuts.filter{it.endUs<=start}.sumOf{it.endUs-it.startUs};kept.add(SubtitleCue(shifted,shifted+end-start,cue.text))}}
        cuts.forEach{cut->if(cut.endUs>start && cut.startUs<cue.endUs){append(minOf(cut.startUs,cue.endUs));start=maxOf(start,cut.endUs)}}
        append(cue.endUs);kept
    }
    fun srt(cues:List<SubtitleCue>):String {
        fun time(us:Long):String {val ms=us/1000;return String.format(Locale.ROOT,"%02d:%02d:%02d,%03d",ms/3600000,ms/60000%60,ms/1000%60,ms%1000)}
        return cues.mapIndexed{i,cue->"${i+1}\n${time(cue.startUs)} --> ${time(cue.endUs)}\n${cue.text}\n"}.joinToString("\n")
    }
}
